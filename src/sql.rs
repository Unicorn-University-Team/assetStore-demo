//! What the public API cannot do (roles, blocked accounts, dates, download counts, deleting accounts) is written
//! as one SQL file. The demo workflow runs it on the server in the `db` container (docs/spec.md); locally it can be
//! run with psql. The tool itself never connects to a database.

use std::fmt::Write;

/// Statements grouped by database, in the order they were added.
#[derive(Default)]
pub struct SqlFile {
    sections: Vec<(&'static str, Vec<String>)>,
}

impl SqlFile {
    pub fn add(&mut self, database: &'static str, statement: String) {
        match self.sections.iter_mut().find(|(name, _)| *name == database) {
            Some((_, statements)) => statements.push(statement),
            None => self.sections.push((database, vec![statement])),
        }
    }

    pub fn is_empty(&self) -> bool {
        self.sections.is_empty()
    }

    pub fn statement_count(&self) -> usize {
        self.sections
            .iter()
            .map(|(_, statements)| statements.len())
            .sum()
    }

    /// psql script: each database in its own transaction, stop at the first error.
    pub fn render(&self) -> String {
        let mut out = String::from(
            "-- Generated by assetstore-demo. Run: psql -v ON_ERROR_STOP=1 -f <this file>\n",
        );
        for (database, statements) in &self.sections {
            let _ = write!(out, "\n\\connect {database}\nBEGIN;\n");
            for statement in statements {
                let _ = writeln!(out, "{statement};");
            }
            out.push_str("COMMIT;\n");
        }
        out
    }
}

/// A single-quoted SQL literal. Values here come from the fixtures and the API (uuids), but quote them anyway.
pub fn quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

/// Accepts only a uuid, so an id from an API answer can never change the statement.
pub fn uuid(value: &str) -> anyhow::Result<String> {
    let ok = value.len() == 36
        && value.chars().enumerate().all(|(i, c)| {
            if [8, 13, 18, 23].contains(&i) {
                c == '-'
            } else {
                c.is_ascii_hexdigit()
            }
        });
    anyhow::ensure!(ok, "not a uuid: {value}");
    Ok(quote(value))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn groups_statements_by_database() {
        let mut sql = SqlFile::default();
        sql.add("identity", "SELECT 1".into());
        sql.add("catalog", "SELECT 2".into());
        sql.add("identity", "SELECT 3".into());
        let text = sql.render();
        assert_eq!(text.matches("\\connect identity").count(), 1);
        assert!(text.find("SELECT 3").unwrap() < text.find("\\connect catalog").unwrap());
    }

    #[test]
    fn quotes_and_checks_uuids() {
        assert_eq!(quote("O'Brien"), "'O''Brien'");
        assert_eq!(
            uuid("72546f10-cac3-4a60-bde2-0a31a3d26bfc").unwrap(),
            "'72546f10-cac3-4a60-bde2-0a31a3d26bfc'"
        );
        assert!(uuid("1' OR '1'='1").is_err());
    }
}
